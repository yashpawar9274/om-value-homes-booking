do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'blog_posts',
    'founder_profiles',
    'founder_projects',
    'customer_stories',
    'flat_tours',
    'property_types',
    'amenities',
    'faqs',
    'site_settings'
  ]
  loop
    execute format('grant select on public.%I to anon, authenticated', table_name);
    execute format('grant insert, update, delete on public.%I to authenticated', table_name);
    execute format('drop policy if exists "Public reads %s" on public.%I', table_name, table_name);
    execute format(
      'create policy "Public reads %s" on public.%I for select to anon, authenticated using (true)',
      table_name,
      table_name
    );
    execute format('drop policy if exists "Admin manages %s" on public.%I', table_name, table_name);
    execute format(
      'create policy "Admin manages %s" on public.%I for all to authenticated using (public.is_content_admin()) with check (public.is_content_admin())',
      table_name,
      table_name
    );
  end loop;
end;
$$;

