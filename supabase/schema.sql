alter table public.founder_profiles
  drop constraint if exists founder_profiles_id_check;
alter table public.founder_profiles
  add column if not exists sort_order integer not null default 1;

do $$
declare
  founder_sequence text;
  founder_max_id bigint;
begin
  founder_sequence := pg_get_serial_sequence('public.founder_profiles', 'id');
  if founder_sequence is null then
    create sequence if not exists public.founder_profiles_id_seq;
    alter sequence public.founder_profiles_id_seq
      owned by public.founder_profiles.id;
    alter table public.founder_profiles
      alter column id set default nextval('public.founder_profiles_id_seq');
    founder_sequence := 'public.founder_profiles_id_seq';
  end if;

  select coalesce(max(id), 0) into founder_max_id
  from public.founder_profiles;
  if founder_max_id = 0 then
    perform setval(founder_sequence::regclass, 1, false);
  else
    perform setval(founder_sequence::regclass, founder_max_id, true);
  end if;
end;
$$;

