-- OM Value Homes content database for the Supabase/Vercel deployment.
-- Run this once in the Supabase SQL Editor after creating the project.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create or replace function public.is_content_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce((select auth.jwt() ->> 'email'), '') = 'omvaluehomes6@gmail.com';
$$;

create table if not exists public.blog_posts (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  excerpt text not null,
  category text not null,
  body text not null,
  seo_title text not null,
  seo_description text not null,
  cover_path text,
  published_at date not null default current_date,
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.founder_profiles (
  id bigint primary key default 1 check (id = 1),
  name text not null,
  role text not null,
  headline text not null,
  bio text not null,
  image_path text,
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.founder_projects (
  id bigint generated by default as identity primary key,
  stage text not null check (stage in ('Previous', 'Latest', 'Upcoming')),
  title text not null,
  status text not null,
  description text not null,
  image_path text,
  sort_order integer not null default 1,
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.customer_stories (
  id bigint generated by default as identity primary key,
  name text not null,
  title text not null,
  story text not null,
  orientation text not null check (orientation in ('portrait', 'landscape')),
  image_path text,
  sort_order integer not null default 1,
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.flat_tours (
  id bigint generated by default as identity primary key,
  title text not null,
  bhk_label text not null unique,
  video_source text not null default 'storage' check (video_source in ('storage', 'youtube')),
  video_path text,
  video_url text,
  embed_html text,
  file_name text,
  content_type text,
  file_size bigint,
  updated_at timestamptz not null default timezone('utc', now())
);

