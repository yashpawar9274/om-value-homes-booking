drop policy if exists "Public reads OM content media" on storage.objects;
create policy "Public reads OM content media"
on storage.objects for select
to anon, authenticated
using (bucket_id in ('content-media', 'flat-tours'));

drop policy if exists "Admin uploads OM content media" on storage.objects;
create policy "Admin uploads OM content media"
on storage.objects for insert
to authenticated
with check (
  bucket_id in ('content-media', 'flat-tours')
  and public.is_content_admin()
  and (
    (bucket_id = 'content-media' and name like 'content/%')
    or (bucket_id = 'flat-tours' and name like 'tours/%')
  )
);

drop policy if exists "Admin updates OM content media" on storage.objects;
create policy "Admin updates OM content media"
on storage.objects for update
to authenticated
using (
  bucket_id in ('content-media', 'flat-tours')
  and public.is_content_admin()
)
with check (
  bucket_id in ('content-media', 'flat-tours')
  and public.is_content_admin()
);

drop policy if exists "Admin deletes OM content media" on storage.objects;
create policy "Admin deletes OM content media"
on storage.objects for delete
to authenticated
using (
  bucket_id in ('content-media', 'flat-tours')
  and public.is_content_admin()
);

